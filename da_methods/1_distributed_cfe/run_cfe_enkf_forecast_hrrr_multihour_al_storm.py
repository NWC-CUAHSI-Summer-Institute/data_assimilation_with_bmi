# ---------------------------------------------------------------------------
# CRPS / CRPSS
# ---------------------------------------------------------------------------
def crps_ensemble(obs, ens):
    n, m = ens.shape
    obs = np.asarray(obs, dtype=float).reshape(n, 1)
    term1 = np.abs(ens - obs).mean(axis=1)
    ens_sorted = np.sort(ens, axis=1)
    i = np.arange(1, m + 1)
    term2 = (2 * i - m - 1) @ ens_sorted.T / (m ** 2)
    return term1 - term2


def crpss(crps_forecast, crps_reference):
    if (crps_reference is None or not np.isfinite(crps_reference)
            or crps_reference == 0.0):
        return float("nan")
    return 1.0 - crps_forecast / crps_reference


