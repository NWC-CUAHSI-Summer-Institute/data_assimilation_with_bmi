def _read_hrrr_lead_dir(lead_dir, cat_id, lo, hi):
    """Read fh{L}/camels_<YYYYMMDD>/<cat>.csv for valid dates in [lo, hi]."""
    days = pd.date_range(lo.normalize(), hi.normalize(), freq="D")
    frames = []
    for d in days:
        f = Path(lead_dir) / f"camels_{d:%Y%m%d}" / f"{cat_id}.csv"
        if f.exists():
            frames.append(pd.read_csv(f))
    if not frames:
        raise FileNotFoundError(
            f"No HRRR forcing for {cat_id} in {lead_dir} "
            f"over {lo:%Y-%m-%d}..{hi:%Y-%m-%d}")
    df = pd.concat(frames, ignore_index=True)
    df["date"] = pd.to_datetime(df["time"]).dt.strftime("%Y-%m-%d %H:%M:%S")
    df = df.drop_duplicates(subset="date").sort_values("date").reset_index(drop=True)
    df["total_precipitation"] = df["APCP_1hr_acc_fcst"].fillna(0.0).clip(lower=0.0)
    df["potential_evaporation"] = enkf.priestley_taylor_pet(
        df["DSWRF"].fillna(0.0).values, df["TMP"].ffill().values)
    return df.set_index("date")


def load_hrrr_lead_dependent_forcing(hrrr_root, cat_id, lead_hours, lo, hi):
    """Return {lead: date-indexed DataFrame} for lead = 1..lead_hours."""
    by_lead = {}
    for lead in range(1, lead_hours + 1):
        lead_dir = Path(hrrr_root) / f"fh{lead:02d}"
        by_lead[lead] = _read_hrrr_lead_dir(lead_dir, cat_id, lo, hi)
    return by_lead


# ---------------------------------------------------------------------------
# Snapshot / restore
# ---------------------------------------------------------------------------
def snapshot_states(models):
    return [(float(m.soil_reservoir["storage_m"]),
             float(m.gw_reservoir["storage_m"]),
             np.array(m.nash_storage, copy=True),
             np.array(m.runoff_queue_m_per_timestep, copy=True))
            for m in models]


def restore_states(models, snap):
    for m, (sm, gw, nash, queue) in zip(models, snap):
        m.soil_reservoir["storage_m"] = sm
        m.gw_reservoir["storage_m"] = gw
        m.nash_storage = nash.copy()
        m.runoff_queue_m_per_timestep = queue.copy()


def apply_spinup_states(models, states_json, rng):
    """
    Override initial ensemble states with those from the 1-year WY2026 spin-up.
    Member 0 gets the exact deterministic spin-up state; members 1+ are perturbed
    by enkf.INIT_STATE_SIGMA so the ensemble has spread from the start.
    """
    with open(states_json) as f:
        s = json.load(f)
    sm_ref   = float(s["soil_storage_m"])
    gw_ref   = float(s["gw_storage_m"])
    nash0_ref = float(s["nash_storage_0"])
    nash1_ref = float(s["nash_storage_1"])
    queue_ref = np.array(s.get("runoff_queue", [0.0, 0.0]), dtype=float)

    for i, m in enumerate(models):
        sm_max = m.soil_reservoir["storage_max_m"]
        gw_max = m.gw_reservoir["storage_max_m"]
        if i == 0:
            scale = 1.0
        else:
            scale = 1.0 + enkf.INIT_STATE_SIGMA * rng.standard_normal()
        m.soil_reservoir["storage_m"] = float(
            np.clip(sm_ref * scale, 1e-6, sm_max))
        m.gw_reservoir["storage_m"] = float(
            np.clip(gw_ref * scale, 1e-6, gw_max))
        m.nash_storage[0] = max(nash0_ref * max(scale, 0.0), 0.0)
        m.nash_storage[1] = max(nash1_ref * max(scale, 0.0), 0.0)
        if len(m.runoff_queue_m_per_timestep) == len(queue_ref):
            m.runoff_queue_m_per_timestep = queue_ref.copy()


def save_checkpoint(models, ol_models, issue_time, cat_id, checkpoint_dir):
    """Save full per-member states at the last issue time for hot-start continuation."""
    rows = []
    for tag, mset in (("da", models), ("ol", ol_models)):
        for i, m in enumerate(mset):
            rows.append({
                "tag":     tag,
                "member":  i,
                "soil_m":  float(m.soil_reservoir["storage_m"]),
                "gw_m":    float(m.gw_reservoir["storage_m"]),
                "nash0":   float(m.nash_storage[0]),
                "nash1":   float(m.nash_storage[1]),
                "queue_0": float(m.runoff_queue_m_per_timestep[0]),
                "queue_1": float(m.runoff_queue_m_per_timestep[1]),
            })
    df = pd.DataFrame(rows)
    df["issue_time"] = issue_time
    Path(checkpoint_dir).mkdir(parents=True, exist_ok=True)
    df.to_parquet(Path(checkpoint_dir) / f"{cat_id}_checkpoint.parquet", index=False)


def apply_checkpoint_states(models, ol_models, checkpoint_parquet):
    """Load per-member states from a prior run's checkpoint for hot-start."""
    df = pd.read_parquet(checkpoint_parquet)
    for tag, mset in (("da", models), ("ol", ol_models)):
        sub = df[df["tag"] == tag].set_index("member")
        for i, m in enumerate(mset):
            row = sub.loc[i]
            sm_max = m.soil_reservoir["storage_max_m"]
            gw_max = m.gw_reservoir["storage_max_m"]
            m.soil_reservoir["storage_m"] = float(np.clip(row["soil_m"], 1e-6, sm_max))
            m.gw_reservoir["storage_m"]   = float(np.clip(row["gw_m"],   1e-6, gw_max))
            m.nash_storage[0] = max(float(row["nash0"]), 0.0)
            m.nash_storage[1] = max(float(row["nash1"]), 0.0)
            if len(m.runoff_queue_m_per_timestep) >= 2:
                m.runoff_queue_m_per_timestep[0] = float(row["queue_0"])
                m.runoff_queue_m_per_timestep[1] = float(row["queue_1"])
    return str(df["issue_time"].iloc[0])   # caller uses to know where to resume


def forecast_step(models, precip_mmh, pet_mmh, fc_rng):
    """One open-loop forecast hour — no DA, no process noise.
    Perturbation: per-member lognormal precip noise (same sigma as assimilation)."""
    n = len(models)
    if PERTURB_FORECAST_FORCING:
        p = precip_mmh * fc_rng.lognormal(-0.5 * enkf.PRECIP_SIGMA ** 2,
                                           enkf.PRECIP_SIGMA, n)
        e = np.maximum(pet_mmh * (1.0 + enkf.PET_SIGMA * fc_rng.standard_normal(n)), 0.0)
    else:
        p = np.full(n, precip_mmh)
        e = np.full(n, max(pet_mmh, 0.0))
    q_mmh = np.empty(n)
    for i, m in enumerate(models):
        m.set_value("atmosphere_water__time_integral_of_precipitation_mass_flux",
                    float(p[i]) / 1000.0)
        m.set_value("water_potential_evaporation_flux",
                    float(e[i]) / 1000.0 / 3600.0)
        m.update()
        q_mmh[i] = m.get_value("land_surface_water__runoff_depth") * 1000.0
    if ADD_FORECAST_PROCESS_NOISE:
        enkf.add_process_noise(models, fc_rng)
    return q_mmh


# ---------------------------------------------------------------------------
# Per-catchment main loop
# ---------------------------------------------------------------------------
def run_catchment(cat_id, args):
    t_start = time.time()
    out_dir = Path(args.out_dir) / cat_id
    out_dir.mkdir(parents=True, exist_ok=True)
    print(f"\n{'='*70}\n{cat_id}: EnKF N={args.n_members} + hourly {args.lead_hours}h "
          f"forecasts {args.issue_start[:10]} .. {args.issue_end[:10]}\n{'='*70}")

    # ── 1. LOAD ───────────────────────────────────────────────────────────────
    params_file = Path(args.params_dir) / cat_id / f"{cat_id}_best_params.json"
    if not params_file.exists():
        params_file = Path(args.params_dir) / f"{cat_id}_best_params.json"
    with open(params_file) as f:
        best_params = json.load(f)["best_parameters"]

    if getattr(args, "nwm_dir", None):
        forcing_csv = enkf.build_nwm_forcing(cat_id, args.nwm_dir, out_dir)
    else:
        forcing_csv = enkf.build_hrrr_forcing(cat_id, args.hrrr_dir, out_dir)
    forcing = enkf.load_forcing(forcing_csv)
    obs_dict, var_dict = enkf.load_observations(Path(args.obs_dir) / f"{cat_id}.csv")
    cfg_path = enkf.write_bmi_config(args.config_file, best_params, forcing_csv,
                                     out_dir / f"{cat_id}_bmi_config_fc.json")

    spin = forcing[(forcing["date"] >= enkf.SPINUP_START)
                   & (forcing["date"] <= enkf.SPINUP_END)].reset_index(drop=True)
    assim = forcing[(forcing["date"] >= enkf.TEST_START)
                    & (forcing["date"] < args.issue_start)].reset_index(drop=True)
    sweep = forcing[(forcing["date"] >= args.issue_start)
                    & (forcing["date"] <= args.issue_end)].reset_index(drop=True)
    forcing_by_date = forcing.set_index("date")

    # lead-dependent HRRR forecast forcing (fh01..fhNN)
    if args.forecast_forcing_dir:
        fc_lo = pd.Timestamp(args.issue_start) + pd.Timedelta(hours=1)
        fc_hi = pd.Timestamp(args.issue_end) + pd.Timedelta(hours=args.lead_hours)
        fc_forcing_by_lead = load_hrrr_lead_dependent_forcing(
            args.forecast_forcing_dir, cat_id, args.lead_hours, fc_lo, fc_hi)
        print(f"  Forecast forcing: HRRR lead-dependent fh01..fh{args.lead_hours:02d} "
              f"from {args.forecast_forcing_dir}")
    else:
        fc_forcing_by_lead = None
        print("  Forecast forcing: HRRR assimilation series (lead-independent, "
              "not recommended for skill evaluation)")
    print(f"  Spinup {len(spin)} h | assimilation {len(assim)} h | "
          f"issue sweep {len(sweep)} h x {args.lead_hours} leads")

    # ── 2. BUILD ──────────────────────────────────────────────────────────────
    rng = np.random.default_rng(args.rng_seed)
    print(f"  Building {args.n_members} DA + {args.n_members} open-loop members...")
    models    = enkf.build_ensemble(args.n_members, str(cfg_path), forcing, rng)
    ol_rng    = np.random.default_rng(args.rng_seed + 777_000)
    ol_models = enkf.build_ensemble(args.n_members, str(cfg_path), forcing, ol_rng)

    # ── 2b. APPLY 1-YEAR SPIN-UP STATES (replaces Pigeon River template) ──────
    if getattr(args, "spinup_states_dir", None):
        sj = Path(args.spinup_states_dir) / f"{cat_id}_spinup_states.json"
        if sj.exists():
            apply_spinup_states(models,    sj, rng)
            apply_spinup_states(ol_models, sj, ol_rng)
            print(f"  Loaded WY2026 spin-up states: {sj.name}")
        else:
            print(f"  WARNING: spinup states not found for {cat_id} — "
                  f"using template (wet soil); run spinup_al_storm.py first")

    diag = {"n_updates": 0, "abs_innov_sum": 0.0, "pyy_sum": 0.0,
            "K_sm_sum": 0.0, "K_gw_sum": 0.0, "K_n0_sum": 0.0, "K_n1_sum": 0.0,
            "mass_lost_mm": 0.0}

    def assimilate_one_hour(row):
        q = enkf.step_all_members(models, float(row.total_precipitation),
                                  float(row.potential_evaporation), rng)
        y_obs   = obs_dict.get(row.date, np.nan)
        krig_var = var_dict.get(row.date, np.nan)
        if not (np.isnan(y_obs) or np.isnan(krig_var)):
            enkf.enkf_update(models, q, y_obs, krig_var, rng, diag)
        enkf.add_process_noise(models, rng)
        return q

    def step_openloop_one_hour(row):
        q = enkf.step_all_members(ol_models, float(row.total_precipitation),
                                  float(row.potential_evaporation), ol_rng)
        enkf.add_process_noise(ol_models, ol_rng)
        return q

    save_mq  = args.save_members
    da_mq_rows = [] if save_mq else None
    ol_mq_rows = [] if save_mq else None
    mq_times   = [] if save_mq else None

    # ── 3. SPINUP + 4. ASSIMILATION (skipped if checkpoint provided) ──────────
    ckpt_file = (Path(args.load_checkpoint_dir) / f"{cat_id}_checkpoint.parquet"
                 if getattr(args, "load_checkpoint_dir", None) else None)
    if ckpt_file and ckpt_file.exists():
        resumed_at = apply_checkpoint_states(models, ol_models, ckpt_file)
        print(f"  Hot-start from checkpoint (issued at {resumed_at}); "
              f"skipping {len(spin)} spinup + {len(assim)} assimilation hours")
    else:
        # ── 3. SPINUP ─────────────────────────────────────────────────────────
        print("  Spinup (both ensembles)...")
        for k, row in enumerate(spin.itertuples()):
            enkf.step_all_members(models,    float(row.total_precipitation), float(row.potential_evaporation), rng)
            enkf.add_process_noise(models, rng)
            enkf.step_all_members(ol_models, float(row.total_precipitation), float(row.potential_evaporation), ol_rng)
            enkf.add_process_noise(ol_models, ol_rng)
            if (k + 1) % 2000 == 0:
                print(f"    spinup {k+1}/{len(spin)} h ({time.time()-t_start:.0f}s)")

        # ── 4. ASSIMILATION up to issue window ────────────────────────────────
        print("  Assimilating up to the issue window...")
        for k, row in enumerate(assim.itertuples()):
            q_da = assimilate_one_hour(row)
            q_ol = step_openloop_one_hour(row)
            if save_mq:
                mq_times.append(row.date)
                da_mq_rows.append(q_da.astype(np.float32))
                ol_mq_rows.append(q_ol.astype(np.float32))
            if (k + 1) % 2000 == 0:
                print(f"    assim {k+1}/{len(assim)} h | updates: {diag['n_updates']} "
                      f"({time.time()-t_start:.0f}s)")

    # ── 5. ISSUE SWEEP ────────────────────────────────────────────────────────
    print("  Issue sweep (assimilate -> snapshot -> 18h forecast -> restore)...")
    member_names = [f"member_{i:04d}" for i in range(args.n_members)]
    fc_meta, fc_rows_da, fc_rows_ol = [], [], []
    state_rows = []

    def run_forecast_18h(model_set, t0_ts, fc_rng_seed, sink):
        """Snapshot → 18 forecast steps → restore. Paired RNG seed for DA+OL."""
        snap = snapshot_states(model_set)
        fc_rng = np.random.default_rng(fc_rng_seed)
        for lead in range(1, args.lead_hours + 1):
            tv = (t0_ts + pd.Timedelta(hours=lead)).strftime("%Y-%m-%d %H:%M:%S")
            frow = None
            if fc_forcing_by_lead is not None:
                try:
                    r = fc_forcing_by_lead[lead].loc[tv]
                    frow = r.iloc[0] if isinstance(r, pd.DataFrame) else r
                except Exception:
                    pass
            if frow is None:
                try:
                    r = forcing_by_date.loc[tv]
                    frow = r.iloc[0] if isinstance(r, pd.DataFrame) else r
                except Exception:
                    frow = forcing_by_date.iloc[-1]  # last available
            qf = forecast_step(model_set,
                               float(frow["total_precipitation"]),
                               float(frow["potential_evaporation"]),
                               fc_rng)
            sink.append(qf.astype(np.float32))
        restore_states(model_set, snap)

    for k, row in enumerate(sweep.itertuples()):
        t0 = row.date
        q_da = assimilate_one_hour(row)
        q_ol = step_openloop_one_hour(row)
        if save_mq:
            mq_times.append(t0)
            da_mq_rows.append(q_da.astype(np.float32))
            ol_mq_rows.append(q_ol.astype(np.float32))

        for i, m in enumerate(models):
            state_rows.append({
                "time":    t0, "member": i,
                "soil_m":  float(m.soil_reservoir["storage_m"]),
                "gw_m":    float(m.gw_reservoir["storage_m"]),
                "nash0":   float(m.nash_storage[0]),
                "nash1":   float(m.nash_storage[1]),
                "queue_0": float(m.runoff_queue_m_per_timestep[0]),
                "queue_1": float(m.runoff_queue_m_per_timestep[1]),
            })

        t0_ts = pd.Timestamp(t0)
        for lead in range(1, args.lead_hours + 1):
            fc_meta.append((t0, lead,
                            (t0_ts + pd.Timedelta(hours=lead)).strftime("%Y-%m-%d %H:%M:%S")))

        # paired RNG seed: DA and OL get the same seed → identical forcing noise
        paired_seed = args.rng_seed * 1_000_003 + k
        run_forecast_18h(models,    t0_ts, paired_seed, fc_rows_da)
        run_forecast_18h(ol_models, t0_ts, paired_seed, fc_rows_ol)

        if (k + 1) % 24 == 0:
            print(f"    issued {k+1}/{len(sweep)} pairs ({time.time()-t_start:.0f}s)")

    # ── 5b. SAVE CHECKPOINT ───────────────────────────────────────────────────
    if getattr(args, "save_checkpoint_dir", None) and sweep is not None and len(sweep):
        last_issue = sweep.iloc[-1]["date"]
        save_checkpoint(models, ol_models, last_issue, cat_id, args.save_checkpoint_dir)
        print(f"  Checkpoint saved at {last_issue}: {args.save_checkpoint_dir}/{cat_id}_checkpoint.parquet")

    for m in models:    m.finalize()
    for m in ol_models: m.finalize()

    # ── 6. SAVE ───────────────────────────────────────────────────────────────
    meta = pd.DataFrame(fc_meta, columns=["issue_time", "lead_hour", "valid_time"])

    def compute_skill(rows, tag):
        fc = pd.concat([meta.copy(),
                        pd.DataFrame(np.vstack(rows), columns=member_names)], axis=1)
        pq = out_dir / f"{cat_id}_forecast_leadtime_{tag}.parquet"
        fc.to_parquet(pq, index=False)
        ens_mean = fc[member_names].mean(axis=1)
        obs = fc["valid_time"].map(obs_dict)
        skill, mask_by_lead = {}, {}
        for lead, g in fc.groupby("lead_hour").groups.items():
            o = obs.loc[g].values.astype(float)
            s = ens_mean.loc[g].values
            finite = np.isfinite(o)
            member_vals = fc.loc[g, member_names].values
            crps_vals = (crps_ensemble(o[finite], member_vals[finite])
                         if finite.any() else np.array([]))
            skill[int(lead)] = {
                "kge":  enkf.kge(o, s),
                "nse":  enkf.nse(o, s),
                "crps": float(np.mean(crps_vals)) if crps_vals.size else float("nan"),
                "n":    int(finite.sum()),
            }
            mask_by_lead[int(lead)] = finite
        print(f"  [{tag}] {pq.name} written ({len(fc)} rows)")
        return pq, skill, mask_by_lead

    fc_pq, skill_da, mask_da = compute_skill(fc_rows_da, "da")
    ol_pq, skill_ol, mask_ol = compute_skill(fc_rows_ol, "openloop")

    for lead in skill_da:
        skill_da[lead]["crpss_vs_openloop"] = crpss(
            skill_da[lead]["crps"], skill_ol[lead]["crps"])

    pd.DataFrame(state_rows).to_parquet(
        out_dir / f"{cat_id}_analysis_states_sweep.parquet", index=False)

    if save_mq:
        member_names_cols = member_names

        def _save_mq(rows, traj_dir, suffix=""):
            d = Path(traj_dir) / cat_id
            d.mkdir(parents=True, exist_ok=True)
            mq = pd.DataFrame(np.vstack(rows), columns=member_names_cols)
            mq.insert(0, "time", mq_times)
            mq.to_parquet(d / f"{cat_id}_member_q{suffix}.parquet", index=False)

        _save_mq(da_mq_rows, args.da_traj_dir)
        _save_mq(ol_mq_rows, args.ol_traj_dir, "_ol")
        print(f"  member_q saved: {len(mq_times)} h")

    with open(out_dir / f"{cat_id}_forecast_summary.json", "w") as f:
        json.dump({
            "cat_id": cat_id, "n_members": args.n_members,
            "issue_window": [args.issue_start, args.issue_end],
            "n_issues": len(sweep), "lead_hours": args.lead_hours,
            "perturb_forecast_forcing": PERTURB_FORECAST_FORCING,
            "forecast_forcing": (f"HRRR fh01..fh{args.lead_hours:02d}: "
                                 f"{args.forecast_forcing_dir}"
                                 if args.forecast_forcing_dir else "HRRR lead-independent"),
            "n_assim_updates": diag["n_updates"],
            "skill_by_lead_da": skill_da,
            "skill_by_lead_ol": skill_ol,
            "runtime_s": round(time.time() - t_start, 1),
        }, f, indent=2)

    l1 = skill_da.get(1, {}); lN = skill_da.get(args.lead_hours, {})
    print(f"  Done {len(sweep)} issues | "
          f"lead-1 KGE={l1.get('kge', float('nan')):.3f} "
          f"CRPSS={l1.get('crpss_vs_openloop', float('nan')):.3f} | "
          f"lead-{args.lead_hours} KGE={lN.get('kge', float('nan')):.3f} | "
          f"{round(time.time()-t_start, 1)}s")
    return {"cat_id": cat_id, "n_issues": len(sweep),
            "lead1_kge": l1.get("kge"), "leadN_kge": lN.get("kge")}


