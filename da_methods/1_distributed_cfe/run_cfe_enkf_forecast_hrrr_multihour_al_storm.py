def main():
    global enkf
    parser = argparse.ArgumentParser(
        description="Hourly-cycled 18h ensemble forecasts — Alabama storm 2026.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter)
    parser.add_argument("--cat-id",     required=True, help="catchment id or 'all'")
    parser.add_argument("--n-members",  type=int, default=600)
    parser.add_argument("--rng-seed",   type=int, default=42)
    parser.add_argument("--lead-hours", type=int, default=LEAD_HOURS)
    parser.add_argument("--issue-start", default=ISSUE_START)
    parser.add_argument("--issue-end",   default=ISSUE_END)
    parser.add_argument("--obs-dir",     default=enkf.DEFAULT_OBS_DIR)
    parser.add_argument("--params-dir",  default=enkf.DEFAULT_PARAMS_DIR)
    parser.add_argument("--cfe-dir",     default=enkf.DEFAULT_CFE_DIR)
    parser.add_argument("--config-file", default=enkf.DEFAULT_CONFIG_FILE)
    parser.add_argument("--hrrr-dir",    default=enkf.DEFAULT_HRRR_DIR,
                        help="root with camels_YYYYMMDD/ subdirs (assimilation forcing, used if --nwm-dir absent)")
    parser.add_argument("--nwm-dir",     default=None,
                        help="NWM operational flat dir (cat-*.csv files); when given, used for DA "
                             "assimilation instead of --hrrr-dir (NWM for DA, HRRR for forecast leads)")
    parser.add_argument("--out-dir",     default=DEFAULT_OUT_DIR)
    parser.add_argument("--forecast-forcing-dir", default=None,
                        help="HRRR root with fh01..fh18/camels_YYYYMMDD/ "
                             "(built by download_hrrr_al_storm.py --all-leads)")
    parser.add_argument("--da-traj-dir", default=DEFAULT_DA_TRAJ_DIR,
                        help="where to write DA member_q trajectories (for route_forecast.py warm-up)")
    parser.add_argument("--ol-traj-dir", default=DEFAULT_OL_TRAJ_DIR,
                        help="where to write open-loop member_q trajectories")
    parser.add_argument("--save-members", action="store_true",
                        help="save per-member hourly runoff (needed for route_forecast.py warm-up)")
    parser.add_argument("--spinup-states-dir", default=None,
                        help="dir with <cat>_spinup_states.json from spinup_al_storm.py; "
                             "replaces the wet Pigeon River template initial states with "
                             "proper dry-summer Alabama Oct 2026 states (strongly recommended)")
    parser.add_argument("--save-checkpoint-dir", default=None,
                        help="dir to write <cat>_checkpoint.parquet (full per-member states "
                             "at the last issue hour) for hot-start of a future extension run")
    parser.add_argument("--load-checkpoint-dir", default=None,
                        help="dir with <cat>_checkpoint.parquet from a prior run; "
                             "skips spinup + pre-issue assimilation replay (hot-start)")
    args = parser.parse_args()

    import sys as _sys
    _sys.path.insert(0, args.cfe_dir)
    import bmi_cfe as _bmi_cfe
    enkf.bmi_cfe = _bmi_cfe

    if args.cat_id == "all":
        cat_ids = sorted(p.stem for p in Path(args.obs_dir).glob("cat-*.csv"))
        have_p  = {q.parent.name for q in
                   Path(args.params_dir).glob("cat-*/cat-*_best_params.json")}
        cat_ids = [c for c in cat_ids if c in have_p]
        print(f"Running {len(cat_ids)} catchments | "
              f"issue sweep: {args.issue_start[:10]} .. {args.issue_end[:10]}")
    else:
        cat_ids = [args.cat_id]

    Path(args.out_dir).mkdir(parents=True, exist_ok=True)
    summaries, failed = [], []
    for cat_id in cat_ids:
        try:
            s = run_catchment(cat_id, args)
            summaries.append(s)
        except Exception:
            print(f"\nFAILED: {cat_id}")
            traceback.print_exc()
            failed.append(cat_id)

    if summaries:
        df = pd.DataFrame(summaries)
        df.to_csv(Path(args.out_dir) / "forecast_sweep_summary.csv", index=False)
        print(f"\nMedian lead-1 KGE: {df['lead1_kge'].median():.3f}")
    if failed:
        print(f"\n{len(failed)} FAILED: {', '.join(failed)}")
        sys.exit(1)
    print(f"\nAll {len(cat_ids)} catchment(s) complete.")


if __name__ == "__main__":
    main()
